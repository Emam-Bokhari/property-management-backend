import { Model } from "mongoose";

export type IPackage = {
  name: string;
  description?: string;
  monthlyPrice: number;
  yearlyPrice: number;
  stripeProductId?: string; // Automatically generated by backend via Stripe API
  stripeMonthlyPriceId: string; // Automatically generated by backend via Stripe API
  stripeYearlyPriceId: string; // Automatically generated by backend via Stripe API
  maxProperties: number; // e.g. 2, 5, or -1 for Unlimited
  maxFlats: number; // e.g. 10, 30, or -1 for Unlimited
  features: string[]; // text descriptions for pricing card display
  hasTrial: boolean; // whether package offers a free trial
  trialDays: number; // number of trial days (e.g. 7, 14, or 0)
  isPopular?: boolean;
  isActive: boolean;
  isDeleted?: boolean;
};

export type PackageModel = Model<IPackage>;
